// Copies the compiled TornadoRelayerPaymaster (abi + creation bytecode) into the relayer package so the
// service can deploy its own worker contract without Foundry at runtime. Run after `forge build`.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, '..', '..', 'contracts', 'out', 'TornadoRelayerPaymaster.sol', 'TornadoRelayerPaymaster.json');
const artifact = JSON.parse(readFileSync(src, 'utf8'));
const out = `// Generated by scripts/gen-artifacts.mjs from contracts/out — do not edit.
// TornadoRelayerPaymaster (standalone), solc ${artifact.metadata?.compiler?.version ?? 'unknown'}.
export const paymasterArtifact = {
  abi: ${JSON.stringify(artifact.abi)} as const,
  bytecode: ${JSON.stringify(artifact.bytecode.object)} as \`0x\${string}\`,
};
`;
writeFileSync(join(here, '..', 'src', 'generated', 'paymaster-artifact.ts'), out);
console.log('wrote relayer/src/generated/paymaster-artifact.ts', (artifact.bytecode.object.length - 2) / 2, 'bytes');
